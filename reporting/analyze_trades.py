# Time-of-day buckets. Half-open intervals: [start, end).
TIME_BLOCKS: list[tuple[str, dtime, dtime]] = [
    ("09:30-10:30", dtime(9, 30),  dtime(10, 30)),
    ("10:30-11:30", dtime(10, 30), dtime(11, 30)),
    ("11:30-12:30", dtime(11, 30), dtime(12, 30)),
    ("12:30-13:30", dtime(12, 30), dtime(13, 30)),
    ("13:30-14:30", dtime(13, 30), dtime(14, 30)),
    ("14:30-16:00", dtime(14, 30), dtime(16, 0)),
]

DAY_ORDER = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday"]

# Map common column-name variations -> canonical name.
COLUMN_ALIASES: dict[str, str] = {
    "symbol": "symbol",
    "ticker": "symbol",
    "entry date": "entry_date",
    "entry_date": "entry_date",
    "entry time": "entry_time",
    "entry_time": "entry_time",
    "entry price": "entry_price",
    "entry_price": "entry_price",
    "exit date": "exit_date",
    "exit_date": "exit_date",
    "exit time": "exit_time",
    "exit_time": "exit_time",
    "exit price": "exit_price",
    "exit_price": "exit_price",
    "shares": "shares",
    "quantity": "shares",
    "qty": "shares",
    "p&l": "pnl",
    "pnl": "pnl",
    "profit": "pnl",
    "profit/loss": "pnl",
    # 'Strategy' from our weekly_tradelog.py maps to 'setup_type'
    "setup type": "setup_type",
    "setup_type": "setup_type",
    "setup": "setup_type",
    "strategy": "setup_type",       # our column name
    "strategy_name": "setup_type",  # alternate our column name
}

REQUIRED_COLUMNS = {
    "symbol", "entry_date", "entry_time", "entry_price",
    "exit_date", "exit_time", "exit_price", "shares", "pnl", "setup_type",
}


